"""Generate frontend contracts from the backend's Pydantic models."""
import json
from pathlib import Path
from pydantic import BaseModel
from backend import contracts


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:
        return ' | '.join(ts_type(part) for part in schema['anyOf'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'const' in schema:
        return json.dumps(schema['const'])
    kind = schema.get('type')
    if kind == 'array':
        return f'Array<{ts_type(schema["items"])}>'
    return {'string': 'string', 'integer': 'number', 'number': 'number',
            'boolean': 'boolean', 'null': 'null', 'object': 'Record<string, unknown>'}.get(kind, 'unknown')


def output():
    parts = ['// Generated by python -m scripts.export_contracts. Do not edit manually.']
    for name, model in vars(contracts).items():
        if isinstance(model, type) and issubclass(model, BaseModel) and model.__module__ == contracts.__name__ and name != 'Contract':
            schema = model.model_json_schema()
            required = schema.get('required', [])
            fields = [f'  {field}{"" if field in required else "?"}: {ts_type(value)};'
                      for field, value in schema.get('properties', {}).items()]
            parts.append(f'export interface {name} {{\n' + '\n'.join(fields) + '\n}')
    return '\n\n'.join(parts) + '\n'


if __name__ == '__main__':
    destination = Path(__file__).resolve().parent.parent / 'frontend/src/contracts.ts'
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(output(), encoding='utf-8')
    print(f'Updated {destination}')
